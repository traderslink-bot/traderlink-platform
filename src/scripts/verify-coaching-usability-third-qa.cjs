// Regression checks for UX18–UX20; all observations must pass.
// COACHING_UX_EDGE_QA=1 COACHING_UX_THIRD_QA=1 node src/scripts/verify-coaching-usability-browser.cjs
module.exports = async function ({page, go, capture, assert}) {
    const observations=[];
    const record=(id,status,evidence)=>observations.push({id,status,evidence});
    await go('teaching');
    await page.getByText('Edit lesson',{exact:true}).click();
    const editor=page.locator('form').filter({has:page.getByRole('button',{name:'Save lesson',exact:true})});
    const title=editor.getByRole('textbox',{name:'Title',exact:true});
    const status=editor.getByRole('combobox',{name:'Status',exact:true});
    await title.fill('QA saved lesson pending edit');
    await page.evaluate(()=>window.actionMode='deferred');
    await editor.getByRole('button',{name:'Save lesson',exact:true}).click();
    await page.waitForFunction(()=>window.pendingActions?.length===1);
    assert(await title.isDisabled());
    const submitted=await page.evaluate(()=>window.actionCalls[0].data.status);
    const delivery=editor.getByRole('combobox',{name:'Delivery',exact:true});
    assert(await status.isDisabled());
    assert(await delivery.isDisabled());
    assert.equal((await status.innerText()).toLowerCase(),submitted);
    assert.equal(await page.evaluate(()=>window.actionCalls[0].data.title),'QA saved lesson pending edit');
    await status.scrollIntoViewIfNeeded();
    await capture('saved-lesson-pending-status');
    await page.evaluate(()=>{window.actionMode='error';window.pendingActions.splice(0).forEach(resolve=>resolve());});
    await editor.getByRole('alert').waitFor();
    await page.waitForFunction(()=>!document.querySelector('details form fieldset')?.disabled);
    assert.equal(await title.inputValue(),'QA saved lesson pending edit');
    assert(await status.isEnabled());
    assert(await delivery.isEnabled());
    const requestId=await page.evaluate(()=>window.actionCalls[0].data.requestId);
    await editor.getByRole('button',{name:'Save lesson',exact:true}).click();
    await page.waitForFunction(()=>window.actionCalls.length===2);
    assert.equal(await page.evaluate(()=>window.actionCalls[1].data.requestId),requestId);
    await status.click();await page.getByRole('option',{name:'Draft',exact:true}).click();
    await delivery.click();await page.getByRole('option',{name:'Recorded',exact:true}).click();
    await page.evaluate(()=>window.actionMode='deferred');
    await editor.getByRole('button',{name:'Save lesson',exact:true}).click();
    await page.waitForFunction(()=>window.actionCalls.length===3&&window.pendingActions.length===1);
    assert.equal(await page.evaluate(()=>window.actionCalls[2].data.status),'draft');
    assert.equal(await page.evaluate(()=>window.actionCalls[2].data.deliveryKind),'recorded');
    assert.notEqual(await page.evaluate(()=>window.actionCalls[2].data.requestId),requestId);
    assert(await status.isDisabled());assert(await delivery.isDisabled());
    await page.evaluate(()=>{window.actionMode='success';window.pendingActions.splice(0).forEach(resolve=>resolve());});
    await page.waitForFunction(()=>!document.querySelector('details form fieldset')?.disabled);
    assert(await status.isEnabled());assert(await delivery.isEnabled());
    assert.equal(await status.innerText(),'Draft');
    assert.equal(await delivery.innerText(),'Recorded');
    record('saved-lesson-select-pending','PASS',{submittedStatus:submitted,note:'Status/Delivery and text lock while saving; captured title/status/delivery are preserved. Successful synthetic completion restores editing without resetting values.'});
    record('saved-lesson-rejection','PASS','Rejected isolated edit retains text/status and unlocks controls. Unchanged retry reuses request ID; changing selectors creates a new request ID.');

    await go('student');
    const picker=page.getByRole('button',{name:'Select chart',exact:true});
    await picker.focus();
    assert(await picker.evaluate(el=>document.activeElement===el));
    let opened=0;
    const onChooser=()=>{opened++;};
    page.on('filechooser',onChooser);
    await picker.press('Enter');
    await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
    const enter=opened;
    await picker.press('Space');
    await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
    const keyboard=opened;
    await picker.click();
    await page.waitForEvent('filechooser',{timeout:1000}).catch(()=>{});
    page.off('filechooser',onChooser);
    assert(opened>keyboard,'Pointer control must open a file chooser in this browser');
    assert(enter>0&&keyboard>enter);
    record('chart-picker-keyboard','PASS',{enterOpened:enter,spaceOpened:keyboard-enter,pointerOpened:opened-keyboard,note:'No file was selected or uploaded. Chooser events compare keyboard and pointer activation of the actual picker.'});

    await go('teaching');
    await page.getByRole('textbox',{name:'Title',exact:true}).first().fill('QA hidden audience check');
    const audience=page.getByRole('combobox',{name:'Audience',exact:true});
    await audience.click();await page.getByRole('option',{name:'Selected students',exact:true}).click();
    await page.getByRole('checkbox',{name:'Alex Rivers',exact:true}).check();
    await audience.click();await page.getByRole('option',{name:'All students',exact:true}).click();
    await page.evaluate(()=>window.actionMode='error');
    await page.getByRole('button',{name:'Save draft',exact:true}).click();
    await page.waitForFunction(()=>window.actionCalls.length===1);
    assert.equal(await page.evaluate(()=>window.actionCalls[0].data.relationshipId??null),null);
    assert.equal(await page.evaluate(()=>window.actionCalls[0].data.audienceMode),'all_students');
    record('hidden-recipient-payload','PASS','Switching from selected students to All students omits hidden relationship IDs from the submitted draft.');

    await go('work','multi-session');
    await page.getByRole('combobox',{name:'Work status',exact:true}).click();
    await page.getByRole('option',{name:'All statuses',exact:true}).click();
    const session=page.getByRole('link',{name:'Open session',exact:true}).filter({visible:true});
    const links=await session.evaluateAll(els=>els.map(el=>el.getAttribute('href')));
    assert.equal(links.length,2);
    const expected=await page.evaluate(()=>window.snapshot.coachingSessions.map(session=>`/communities/${window.snapshot.community.slug}/workspace/students/${session.relationshipId}#coaching-session-${session.sessionId}`));
    assert(links.every(href=>expected.includes(href)));
    record('work-session-destination','PASS',{links,note:'Coaching Work links include the exact selected-session ID, consistently with the secondary Sessions page.'});
    await go('student','multi-session');
    for(const link of links) assert.equal(await page.locator(link.slice(link.indexOf('#'))).count(),1);
    await go('work','multi-session');
    await page.getByRole('button',{name:'Custom',exact:true}).click();
    await page.getByLabel('Start date',{exact:true}).fill('2035-02-10');
    await page.getByLabel('End date',{exact:true}).fill('2035-02-01');
    assert(await page.getByText('End date must be on or after the start date.',{exact:true}).isVisible());
    assert.equal(await page.getByLabel('End date',{exact:true}).getAttribute('aria-invalid'),'true');
    assert.equal(await page.getByText('No work matches your filters',{exact:true}).count(),0);
    assert.equal(await page.getByText('Total due',{exact:true}).count(),0);
    assert.equal(await page.getByLabel('Start date',{exact:true}).inputValue(),'2035-02-10');
    assert.equal(await page.getByLabel('End date',{exact:true}).inputValue(),'2035-02-01');
    await page.getByRole('alert').scrollIntoViewIfNeeded();
    await capture('reversed-date-range');
    await page.getByLabel('End date',{exact:true}).fill('2035-02-10');
    assert.equal(await page.getByLabel('End date',{exact:true}).getAttribute('aria-invalid'),'false');
    assert.equal(await page.getByRole('alert').count(),0);
    record('reversed-date-range','PASS','Reversed dates show field/region errors, preserve both values and suppress misleading counts/no-match guidance. Same-day dates restore valid filtering.');
    await page.getByLabel('End date',{exact:true}).fill('2035-02-01');
    await page.getByRole('button',{name:'Clear filters',exact:true}).click();
    assert.equal(await page.getByLabel('Start date',{exact:true}).count(),0);
    assert.equal(await page.getByRole('alert').count(),0);
    record('reversed-date-recovery','PASS','Correcting the end date or Clear filters recovers without changing records.');
    return observations;
};
