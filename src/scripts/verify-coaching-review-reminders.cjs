const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const vm = require('node:vm');
const root = path.resolve(__dirname, '../..');
const source = fs.readFileSync(path.join(root, 'src/modules/communities/contracts/coaching-review-workspace.ts'), 'utf8');
const compiled = ts.transpileModule(source, {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022},reportDiagnostics:true});
assert.equal(compiled.diagnostics.length, 0);
const exportsObject = {};
vm.runInNewContext(compiled.outputText, {exports:exportsObject});
const {previousDeliveredFocus, coachingReviewLabel} = exportsObject;
const review = (reviewId, deliveredAtUtc, overrides={}) => ({reviewId, relationshipId:'student-a', nextFocus:'Practice entries', deliveredAtUtc, cancelledAtUtc:null, ...overrides});
const old = review('old','2026-10-01T12:00:00.000Z',{updatedAtUtc:'2026-10-10T12:00:00.000Z'});
const recent = review('recent','2026-10-08T12:00:00.000Z');
const scheduled = review('scheduled',null,{updatedAtUtc:'2026-09-01T12:00:00.000Z'});
assert.equal(previousDeliveredFocus([old,recent,scheduled],scheduled).reviewId,'recent');
assert.equal(previousDeliveredFocus([recent,old],scheduled).reviewId,'recent');
assert.equal(previousDeliveredFocus([old,recent],recent).reviewId,'old');
assert.equal(previousDeliveredFocus([review('other','2026-10-09T12:00:00.000Z',{relationshipId:'student-b'}),recent],scheduled).reviewId,'recent');
assert.equal(previousDeliveredFocus([review('blank','2026-10-09T12:00:00.000Z',{nextFocus:'  '}),review('cancelled','2026-10-09T12:00:00.000Z',{cancelledAtUtc:'2026-10-10T12:00:00.000Z'}),recent],scheduled).reviewId,'recent');
assert.equal(previousDeliveredFocus([scheduled],scheduled),undefined);
assert.equal(coachingReviewLabel('trade','custom'),'Trade review');
assert.equal(coachingReviewLabel('strategy','custom'),'Strategy review');
assert.equal(coachingReviewLabel('trading_day','custom'),'Trading-day / session review');
const navigation=fs.readFileSync(path.join(root,'app/(dashboard)/communities/coach-workspace-navigation.tsx'),'utf8');
assert.ok(navigation.includes('coachingReviewLabel(review.workspaceKind,review.reviewType)'));
console.log('PASS: previous delivered focus, scheduled drafts, delivery order, historical cutoff, student isolation, exclusions and review labels');
